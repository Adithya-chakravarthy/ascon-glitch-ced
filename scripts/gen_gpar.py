# Generates ascon_gpar.v: a k-group parity checker for the Ascon state.
# The parity of each group of next-state bits is predicted from the current state
# (own copy of the S-box) and compared with the stored state one cycle later.
# With --chunk N the prediction is registered in chunks of at most N S-box columns
# (pipelined prediction, two LUT levels before the first register).
#
#   python gen_gpar.py --k 32 --mode interleave --chunk 6 --out ascon_gpar.v
#   python gen_gpar.py --mode file --groups sta_sel24.json --out ascon_gpar.v
#   python gen_gpar.py --selftest

import argparse
import json
import os
import random
import sys

M64 = (1 << 64) - 1
ROT = [(19, 28), (61, 39), (1, 6), (10, 17), (7, 41)]
KMAX = 128


def make_groups(k, mode, seed=1, groups_file=None):
    if mode == "file":
        with open(groups_file) as f:
            data = json.load(f)
        groups = data["groups"] if isinstance(data, dict) else data
        groups = [sorted(set(g)) for g in groups if g]
    elif mode == "word":
        if k != 5:
            sys.exit("--mode word needs --k 5")
        groups = [list(range(64 * w, 64 * w + 64)) for w in range(5)]
    elif mode == "interleave":
        groups = [[i for i in range(320) if i % k == g] for g in range(k)]
    elif mode == "random":
        idx = list(range(320))
        random.Random(seed).shuffle(idx)
        groups = [sorted(idx[g::k]) for g in range(k)]
    else:
        sys.exit(f"unknown mode {mode}")
    flat = sorted(i for g in groups for i in g)
    if flat != list(range(320)):
        sys.exit("groups must cover every bit 0..319 exactly once")
    if not 1 <= len(groups) <= KMAX:
        sys.exit(f"number of groups must be 1..{KMAX}")
    return groups


def predictor_terms(group):
    odd = set()
    for i in group:
        w, b = divmod(i, 64)
        for off in (0, ROT[w][0], ROT[w][1]):
            odd ^= {64 * w + (b + off) % 64}
    return sorted(odd)


def chunk_terms(terms, cmax):
    if not cmax:
        return [terms]
    bycol = {}
    for i in terms:
        bycol.setdefault(i % 64, []).append(i)
    cols = sorted(bycol)
    return [sorted(i for c in cols[j:j + cmax] for i in bycol[c]) for j in range(0, len(cols), cmax)] or [[]]


def rotr(x, r):
    return ((x >> r) | (x << (64 - r))) & M64


def sbox_layer(S, rc):
    x0, x1, x2, x3, x4 = S
    x2 ^= rc
    b0, b1, b2, b3, b4 = x0 ^ x4, x1, x2 ^ x1, x3, x4 ^ x3
    c0 = b0 ^ ((~b1 & M64) & b2); c1 = b1 ^ ((~b2 & M64) & b3); c2 = b2 ^ ((~b3 & M64) & b4)
    c3 = b3 ^ ((~b4 & M64) & b0); c4 = b4 ^ ((~b0 & M64) & b1)
    return [c0 ^ c4, c1 ^ c0, ~c2 & M64, c3 ^ c2, c4]


def full_round(S, rc):
    d = sbox_layer(S, rc)
    return [d[w] ^ rotr(d[w], ROT[w][0]) ^ rotr(d[w], ROT[w][1]) for w in range(5)]


def bit(S, i):
    return (S[i // 64] >> (i % 64)) & 1


def selftest():
    rnd = random.Random(5)
    configs = [(1, "interleave"), (5, "word")] + [(k, m) for k in (2, 3, 8, 16, 32, 64, 128)
                                                  for m in ("interleave", "random")]
    for k, mode in configs:
        groups = make_groups(k, mode, seed=3)
        terms = [predictor_terms(g) for g in groups]
        for _ in range(50):
            S = [rnd.getrandbits(64) for _ in range(5)]
            r = rnd.randrange(12)
            rc = ((0xF - r) << 4) | r
            d, nxt = sbox_layer(S, rc), full_round(S, rc)
            for g, t in zip(groups, terms):
                pred = 0
                for i in t:
                    pred ^= bit(d, i)
                act = 0
                for i in g:
                    act ^= bit(nxt, i)
                assert pred == act, (k, mode)
    print("selftest: predicted group parities match the real next state for all", len(configs), "groupings")


def xor_expr(name, idx, per_line=8):
    if not idx:
        return "1'b0"
    parts = [f"{name}[{i}]" for i in idx]
    lines = [" ^ ".join(parts[j:j + per_line]) for j in range(0, len(parts), per_line)]
    return (" ^\n" + " " * 21).join(lines)


def emit(groups, k_label, mode, seed, out_v, chunk=0):
    k = len(groups)
    terms = [predictor_terms(g) for g in groups]
    chunks = [chunk_terms(t, chunk) for t in terms]
    chunk_group = [g for g, cl in enumerate(chunks) for _ in cl]
    n_terms = sum(len(t) for t in terms)
    cols = sum(len({i % 64 for i in t}) for t in terms)
    same = next(((g[0], g[1]) for g in groups if len(g) >= 2), None)
    diff = (groups[0][0], groups[1][0]) if k >= 2 else None

    L = []
    L.append("// Generated by gen_gpar.py, do not edit.")
    L.append(f"// k = {k} groups ({mode}" + (f", seed {seed}" if mode == "random" else "") + f"), "
             f"{min(map(len, groups))}..{max(map(len, groups))} bits per group, {cols} (group, column) terms"
             + (f", {len(chunk_group)} chunk registers" if chunk else ""))
    L.append("// bit index i = 64*w + b; group list in the .json file next to this one")
    L.append("module ascon_gpar_check (")
    L.append("    input  wire        clk,")
    L.append("    input  wire        rst,")
    L.append("    input  wire        in_round,     // high during permutation rounds")
    L.append("    input  wire [63:0] x0, x1, x2, x3, x4,")
    L.append("    input  wire [7:0]  rc,")
    L.append("    output reg         err = 1'b0")
    L.append(");")
    L.append(f"    localparam integer K = {k};")
    L.append("")
    L.append("    // separate copy of the S-box layer")
    L.append("    wire [63:0] a2 = x2 ^ {56'd0, rc};")
    L.append("    wire [63:0] b0 = x0 ^ x4, b1 = x1, b2 = a2 ^ x1, b3 = x3, b4 = x4 ^ x3;")
    L.append("    wire [63:0] c0 = b0 ^ (~b1 & b2), c1 = b1 ^ (~b2 & b3), c2 = b2 ^ (~b3 & b4);")
    L.append("    wire [63:0] c3 = b3 ^ (~b4 & b0), c4 = b4 ^ (~b0 & b1);")
    L.append("    wire [319:0] d = {c4, c3 ^ c2, ~c2, c1 ^ c0, c0 ^ c4};   // {d4,d3,d2,d1,d0}")
    L.append("    wire [319:0] s = {x4, x3, x2, x1, x0};                    // stored state")
    L.append("")
    if not chunk:
        L.append("    // predicted group parities of the next state")
        L.append("    wire [K-1:0] p;")
        for g, t in enumerate(terms):
            L.append(f"    assign p[{g}] = {xor_expr('d', t)};")
        L.append("")
    else:
        nch = len(chunk_group)
        L.append("    // chunk parities, registered together with the state")
        L.append(f"    localparam integer NCH = {nch};")
        L.append("    wire [NCH-1:0] ch;")
        L.append("    // KEEP: one LUT per column term (pc_*) and one per chunk")
        n = 0
        for g, cl in enumerate(chunks):
            for c in cl:
                names = []
                bycol = {}
                for i in c:
                    bycol.setdefault(i % 64, []).append(i)
                for col in sorted(bycol):
                    nm = f"pc_{n}_{col}"
                    names.append(nm)
                    L.append(f"    (* keep = \"true\" *) wire {nm} = {' ^ '.join(f'd[{i}]' for i in bycol[col])};")
                L.append(f"    assign ch[{n}] = {' ^ '.join(names) if names else chr(49) + chr(39) + 'b0'};   // group {g}")
                n += 1
        L.append("    reg [NCH-1:0] chunk_q = {NCH{1'b0}};")
        L.append("    always @(posedge clk) chunk_q <= ch;")
        L.append("")
        L.append("    // group prediction = XOR of its chunk registers (next cycle)")
        L.append("    wire [K-1:0] pred_q;")
        n = 0
        for g, cl in enumerate(chunks):
            idx = list(range(n, n + len(cl)))
            n += len(cl)
            L.append(f"    assign pred_q[{g}] = {xor_expr('chunk_q', idx)};")
        L.append("")
    L.append("    // parity of each group of the stored state")
    L.append("    wire [K-1:0] a;")
    for g, grp in enumerate(groups):
        L.append(f"    assign a[{g}] = {xor_expr('s', grp)};")
    L.append("")
    if not chunk:
        L.append("    reg [K-1:0] pred_q  = {K{1'b0}};")
    L.append("    reg         valid_q = 1'b0;")
    L.append("    always @(posedge clk) begin")
    if not chunk:
        L.append("        pred_q  <= p;")
    L.append("        valid_q <= in_round && !rst;")
    L.append("        err     <= valid_q && (|(a ^ pred_q));")
    L.append("    end")
    L.append("endmodule")
    L.append("")
    L.append("// testbench only")
    L.append("module ascon_gpar_info (")
    L.append("    output wire [7:0] k,")
    L.append("    output wire       has_same, has_diff,")
    L.append("    output wire [8:0] same_a, same_b,   // two bits in the same group")
    L.append("    output wire [8:0] diff_a, diff_b    // two bits in different groups")
    L.append(");")
    L.append(f"    assign k = 8'd{k};")
    L.append(f"    assign has_same = 1'b{1 if same else 0};")
    L.append(f"    assign has_diff = 1'b{1 if diff else 0};")
    sa, sb = same if same else (0, 0)
    da, db = diff if diff else (0, 0)
    L.append(f"    assign same_a = 9'd{sa};  assign same_b = 9'd{sb};")
    L.append(f"    assign diff_a = 9'd{da};  assign diff_b = 9'd{db};")
    L.append("endmodule")
    with open(out_v, "w", newline="\n") as f:
        f.write("\n".join(L) + "\n")
    out_j = os.path.splitext(out_v)[0] + ".json"
    with open(out_j, "w") as f:
        json.dump({"k": k, "mode": mode, "seed": seed, "label": k_label, "chunk": chunk,
                   "chunk_group": chunk_group, "groups": groups}, f)
    return k, n_terms, cols, out_j


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--k", type=int, default=8)
    ap.add_argument("--mode", default="interleave", choices=["interleave", "random", "word", "file"])
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--groups", default=None, help="JSON file for --mode file")
    ap.add_argument("--out", default="ascon_gpar.v")
    ap.add_argument("--chunk", type=int, default=0,
                    help="max S-box columns per registered chunk (0 = no pipelining)")
    ap.add_argument("--selftest", action="store_true")
    args = ap.parse_args()
    if args.selftest:
        selftest()
        return
    groups = make_groups(args.k, args.mode, args.seed, args.groups)
    label = f"{args.mode}{len(groups)}" + (f"s{args.seed}" if args.mode == "random" else "")
    if args.chunk and not 1 <= args.chunk <= 6:
        sys.exit("--chunk must be 0..6")
    k, n_terms, cols, out_j = emit(groups, label, args.mode, args.seed, args.out, args.chunk)
    print(f"wrote {args.out}  (k={k}, {args.mode}, {n_terms} S-box bits in {cols} column terms"
          + (f", pipelined prediction, chunks of <= {args.chunk} columns)" if args.chunk else ")"))
    print(f"wrote {out_j}")


if __name__ == "__main__":
    main()
